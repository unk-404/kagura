#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Op {
    Halt = 0,
    LoadConst = 1,
    LoadLocal = 2,
    StoreLocal = 3,
    Add = 4,
    Sub = 5,
    Mul = 6,
    Div = 7,
    Mod = 8,
    Lt = 9,
    Le = 10,
    Gt = 11,
    Ge = 12,
    Eq = 13,
    Ne = 14,
    StrictEq = 15,
    StrictNotEq = 16,
    Neg = 17,
    Not = 18,
    Jump = 19,
    JumpIfFalse = 20,
    JumpIfTrue = 21,
    CallName = 22,
    Print = 23,
    Pop = 24,
    Return = 25,
    Dup = 26,
    CallHost = 27,
    NewObject = 28,
    GetProp = 29,
    SetProp = 30,
}

impl Op {
    pub fn from_byte(byte: u8) -> Option<Self> {
        Some(match byte {
            0 => Self::Halt,
            1 => Self::LoadConst,
            2 => Self::LoadLocal,
            3 => Self::StoreLocal,
            4 => Self::Add,
            5 => Self::Sub,
            6 => Self::Mul,
            7 => Self::Div,
            8 => Self::Mod,
            9 => Self::Lt,
            10 => Self::Le,
            11 => Self::Gt,
            12 => Self::Ge,
            13 => Self::Eq,
            14 => Self::Ne,
            15 => Self::StrictEq,
            16 => Self::StrictNotEq,
            17 => Self::Neg,
            18 => Self::Not,
            19 => Self::Jump,
            20 => Self::JumpIfFalse,
            21 => Self::JumpIfTrue,
            22 => Self::CallName,
            23 => Self::Print,
            24 => Self::Pop,
            25 => Self::Return,
            26 => Self::Dup,
            27 => Self::CallHost,
            28 => Self::NewObject,
            29 => Self::GetProp,
            30 => Self::SetProp,
            _ => return None,
        })
    }
}
